import { createHash } from 'node:crypto';
import type { InstallerOs } from '@remyral/protocol';

/**
 * Bootstrap scripts for Fleet → "Add machine" (p5-worker-onboarding, docs/design/p5-worker-onboarding.md).
 *
 * A bootstrap script is tiny, deterministic and contains **no secret**: the master origin, the release
 * version, the kit file name and the kit's SHA-256 from the signed installer index. It downloads the kit
 * from the same origin, refuses it unless the SHA-256 matches, keeps it in the program directory (so
 * `uninstall` stays available) and runs the kit's installer with the worker URL. The console shows the
 * script's own SHA-256 next to the command, so the owner runs exactly the script the console described.
 * Pure functions: the same inputs always give the same bytes (and the same hash).
 */
export interface BootstrapInput {
  /** Public https origin (http only for loopback in development). */
  readonly origin: string;
  readonly version: string;
  readonly os: InstallerOs;
  readonly kitFile: string;
  readonly kitSha256: string;
}

export const bootstrapFileName = (os: InstallerOs): string =>
  os === 'windows' ? 'bootstrap.ps1' : 'bootstrap.sh';

/** `wss://host/v1/worker` (ws:// for a loopback http origin). */
export function workerUrl(origin: string): string {
  return `${origin.replace(/^https:/, 'wss:').replace(/^http:/, 'ws:')}/v1/worker`;
}

export const installBase = (origin: string, version: string, os: InstallerOs): string =>
  `${origin}/v1/worker/install/${version}/${os}`;

/** Single-quoted shell / PowerShell literal; inputs are validated, this is defence in depth. */
function quote(value: string): string {
  if (!/^[A-Za-z0-9._:/[\]-]+$/.test(value)) throw new Error(`unsafe value for a bootstrap script: ${value}`);
  return `'${value}'`;
}

function unixScript(i: BootstrapInput): string {
  const kitDir = i.kitFile.replace(/\.tar\.gz$/, '');
  const dest =
    i.os === 'linux'
      ? '/opt/remyral-worker/installer'
      : '/Library/Application Support/RemyralWorker/installer';
  const https = i.origin.startsWith('https://');
  const curl = https ? "curl -fsSL --proto '=https' --tlsv1.2" : 'curl -fsSL';
  const wget = https ? 'wget -q --https-only --secure-protocol=TLSv1_2' : 'wget -q';
  const uname = i.os === 'linux' ? 'Linux' : 'Darwin';
  return `#!/bin/sh
# Remyral worker bootstrap - release ${i.version}, ${i.os}. Generated by ${i.origin} (Machines > Add machine).
# Downloads the installer kit, refuses it unless its SHA-256 matches the signed installer index, keeps it
# in ${dest} and runs its install.sh. Contains no secret. docs/ops/worker-pairing.md
set -eu
umask 022
ORIGIN=${quote(i.origin)}
KIT=${quote(i.kitFile)}
KIT_SHA256=${quote(i.kitSha256)}
MASTER_URL=${quote(workerUrl(i.origin))}
DEST='${dest}'
die() { printf 'remyral bootstrap: %s\\n' "$*" >&2; exit 1; }
[ "$(uname -s)" = ${uname} ] || die "this bootstrap is for ${i.os}; pick the right system in Machines > Add machine"
[ "$(id -u)" = 0 ] || die "run it with sudo"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
url="$ORIGIN/v1/worker/install/${i.version}/${i.os}/$KIT"
echo "==> downloading $url"
if command -v curl >/dev/null 2>&1; then ${curl} -o "$tmp/$KIT" "$url" || die "download failed"
elif command -v wget >/dev/null 2>&1; then ${wget} -O "$tmp/$KIT" "$url" || die "download failed"
else die "curl or wget is required"; fi
if command -v sha256sum >/dev/null 2>&1; then sum=$(sha256sum "$tmp/$KIT" | cut -d' ' -f1); else sum=$(shasum -a 256 "$tmp/$KIT" | cut -d' ' -f1); fi
[ "$sum" = "$KIT_SHA256" ] || die "installer kit SHA-256 mismatch (expected $KIT_SHA256, got $sum) - not installing"
echo "==> installer kit SHA-256 verified"
mkdir -p "$DEST"
rm -rf "$DEST/${kitDir}"
tar -xzf "$tmp/$KIT" -C "$DEST"
chown -R 0:0 "$DEST"
chmod -R go-w "$DEST"
exec /bin/bash "$DEST/${kitDir}/install.sh" --master-url "$MASTER_URL" "$@"
`;
}

function windowsScript(i: BootstrapInput): string {
  const kitDir = i.kitFile.replace(/\.zip$/, '');
  return `#Requires -Version 5.1
# Remyral worker bootstrap - release ${i.version}, windows. Generated by ${i.origin} (Machines > Add machine).
# Downloads the installer kit, refuses it unless its SHA-256 matches the signed installer index, keeps it
# in %ProgramFiles%\\RemyralWorker\\installer and runs its install.ps1. Contains no secret.
# Run from an elevated PowerShell. Extra arguments are passed to install.ps1 (e.g. -NoStart).
param([Parameter(ValueFromRemainingArguments = $true)][string[]]$InstallArgs)
Set-StrictMode -Version 3.0
$ErrorActionPreference = 'Stop'
$Origin = ${quote(i.origin)}
$Kit = ${quote(i.kitFile)}
$KitSha256 = ${quote(i.kitSha256)}
$MasterUrl = ${quote(workerUrl(i.origin))}
$principal = [Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()
if (-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) { throw 'run it from an elevated PowerShell (Run as administrator)' }
[Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12
$tmp = Join-Path ([IO.Path]::GetTempPath()) ('remyral-bootstrap-' + [guid]::NewGuid())
New-Item -ItemType Directory -Path $tmp | Out-Null
try {
  $zip = Join-Path $tmp $Kit
  $url = "$Origin/v1/worker/install/${i.version}/windows/$Kit"
  Write-Output "==> downloading $url"
  Invoke-WebRequest -UseBasicParsing -Uri $url -OutFile $zip
  $sum = (Get-FileHash -LiteralPath $zip -Algorithm SHA256).Hash.ToLowerInvariant()
  if ($sum -ne $KitSha256) { throw "installer kit SHA-256 mismatch (expected $KitSha256, got $sum) - not installing" }
  Write-Output '==> installer kit SHA-256 verified'
  $dest = Join-Path $env:ProgramFiles 'RemyralWorker\\installer'
  New-Item -ItemType Directory -Path $dest -Force | Out-Null
  $kitDir = Join-Path $dest '${kitDir}'
  if (Test-Path -LiteralPath $kitDir) { Remove-Item -LiteralPath $kitDir -Recurse -Force }
  Expand-Archive -LiteralPath $zip -DestinationPath $dest
} finally { Remove-Item -LiteralPath $tmp -Recurse -Force -ErrorAction SilentlyContinue }
# Named parameters go through a hashtable: splatting an array would bind '-MasterUrl' positionally.
$kitArgs = @{ MasterUrl = $MasterUrl }
for ($n = 0; $InstallArgs -and $n -lt $InstallArgs.Count; $n++) {
  $a = $InstallArgs[$n]
  if ($a -cnotmatch '^-([A-Za-z]+)$') { throw "unexpected argument '$a' (use -Name value or -Switch)" }
  $name = $Matches[1]
  if ($n + 1 -lt $InstallArgs.Count -and $InstallArgs[$n + 1] -cnotmatch '^-[A-Za-z]+$') { $kitArgs[$name] = $InstallArgs[$n + 1]; $n++ }
  else { $kitArgs[$name] = $true }
}
& (Join-Path $kitDir 'install.ps1') @kitArgs
`;
}

export function bootstrapScript(i: BootstrapInput): string {
  return i.os === 'windows' ? windowsScript(i) : unixScript(i);
}

export const sha256Hex = (text: string): string => createHash('sha256').update(text, 'utf8').digest('hex');

export interface InstallCommands {
  /** Downloads the bootstrap and checks its SHA-256 (fails closed on a mismatch). */
  readonly download: string;
  /** Runs it (as root / Administrator). */
  readonly run: string;
}

/** The two lines the console shows: download + verify, then run. */
export function installCommands(
  i: BootstrapInput,
): InstallCommands & { readonly bootstrapSha256: string; readonly url: string } {
  const file = bootstrapFileName(i.os);
  const url = `${installBase(i.origin, i.version, i.os)}/${file}`;
  const sum = sha256Hex(bootstrapScript(i));
  if (i.os === 'windows') {
    return {
      url,
      bootstrapSha256: sum,
      download:
        `[Net.ServicePointManager]::SecurityProtocol = 'Tls12'; Invoke-WebRequest -UseBasicParsing -Uri '${url}' -OutFile remyral-bootstrap.ps1; ` +
        `if ((Get-FileHash remyral-bootstrap.ps1 -Algorithm SHA256).Hash -ne '${sum.toUpperCase()}') { Remove-Item remyral-bootstrap.ps1; throw 'checksum mismatch: do not run it' }`,
      run: 'powershell -NoProfile -ExecutionPolicy Bypass -File .\\remyral-bootstrap.ps1',
    };
  }
  const check = i.os === 'linux' ? 'sha256sum -c -' : 'shasum -a 256 -c -';
  const curl = i.origin.startsWith('https://') ? "curl -fsSL --proto '=https' --tlsv1.2" : 'curl -fsSL';
  return {
    url,
    bootstrapSha256: sum,
    download: `${curl} -o remyral-bootstrap.sh '${url}' && echo '${sum}  remyral-bootstrap.sh' | ${check}`,
    run: 'sudo sh remyral-bootstrap.sh',
  };
}
