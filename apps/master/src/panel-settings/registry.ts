/**
 * p17-panel-settings (docs/design/p17-panel-settings.md §3): the owner-relevant settings that used to exist only as
 * environment variables and are now stored by the master and edited in the panel. The environment variable stays the
 * default (and the kill switch where it is one); the panel value wins while it is set; "Ortam değişkenine dön" removes
 * it. Secrets are sealed at rest and never returned.
 *
 * A closed catalog: every key, its section, kind, rules and the environment variable it overrides.
 */

export const PANEL_SECTIONS = [
  'notifications',
  'search',
  'network',
  'sessions',
  'jobs',
  'logs',
  'memory',
  'workflows',
  'ops',
] as const;
export type PanelSection = (typeof PANEL_SECTIONS)[number];

export type SettingKind = 'bool' | 'int' | 'number' | 'enum' | 'string' | 'list' | 'secret';
export type SettingValue = boolean | number | string | readonly string[];

export interface SettingDef {
  readonly key: string;
  readonly section: PanelSection;
  readonly kind: SettingKind;
  /** The environment variable this setting overrides (shown in the panel). */
  readonly env: string;
  /** Validates a panel value (secrets: the plain value; never stored unsealed). */
  readonly schema: z.ZodType<SettingValue>;
  readonly options?: readonly string[];
  readonly min?: number;
  readonly max?: number;
  /** The new value takes effect only after a restart of the master. */
  readonly restart?: boolean;
  /** A secret the master generates itself (the owner never types it). */
  readonly generated?: 'random' | 'vapid' | 'ed25519';
  /** The setting changes who / what is trusted: its section needs the confirmation the panel shows. */
  readonly sensitive?: boolean;
  /** Managed by its own flow (a key rotation), not by the section form: hidden from views and section saves. */
  readonly internal?: boolean;
}

const httpsPrefix = z
  .string()
  .max(512)
  .refine((v) => {
    try {
      const u = new URL(v);
      return (
        u.protocol === 'https:' && u.username === '' && u.password === '' && u.search === '' && u.hash === ''
      );
    } catch {
      return false;
    }
  }, 'an https:// URL prefix without credentials, query or fragment');

const originPattern = z
  .string()
  .max(255)
  .regex(/^https:\/\/(\*\.)?[a-z0-9.-]+(:\d{1,5})?$/, 'https://host or https://*.host');

const cidr = z
  .string()
  .max(64)
  .refine((v) => {
    const [a = '', p, ...rest] = v.split('/');
    const fam = isIP(a);
    if (fam === 0 || rest.length > 0) return false;
    if (p === undefined) return true;
    if (!/^\d{1,3}$/.test(p)) return false;
    return Number(p) <= (fam === 4 ? 32 : 128);
  }, 'an IP address or CIDR');

const opsOrigin = z
  .string()
  .max(255)
  .regex(/^https?:\/\/[a-z0-9.-]+(:\d{1,5})?$/i, 'an http(s) origin without path');

const list = (item: z.ZodType<string>, max = 50): z.ZodType<readonly string[]> =>
  z.array(item).max(max).readonly();

