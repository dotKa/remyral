export type SettingKey = (typeof SETTINGS)[number]['key'];

const BY_KEY = new Map(SETTINGS.map((d) => [d.key, d] as const));

export function settingDef(key: string): SettingDef | undefined {
  return BY_KEY.get(key);
}

/** The settings managed by their own flows (key rotation), saved with `{ internal: true }`. */
export function internalDefs(): readonly SettingDef[] {
  return SETTINGS.filter((d) => d.internal === true);
}

/** The settings a section form shows and saves (internal ones are managed by their own flow). */
export function sectionDefs(section: PanelSection): readonly SettingDef[] {
  return SETTINGS.filter((d) => d.section === section && d.internal !== true);
}

export function isPanelSection(v: unknown): v is PanelSection {
  return typeof v === 'string' && (PANEL_SECTIONS as readonly string[]).includes(v);
}
