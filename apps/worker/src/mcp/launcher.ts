import { chmod, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { mcpRuntimeName, mcpSecretEnvName, type McpSpec } from '@remyral/protocol';
import type { SecretString } from '../secrets/ref.js';
import type { McpServerExec } from './install.js';

/**
 * p14-mcp-stdio (docs/design/p14-mcp-skills.md §14.3): how a runtime starts a local MCP server. Every runtime is given
 * the same command — the job's Node running `remyral-mcp-launch.mjs <spec file>` — never the package's own binary,
 * never a shell, never a secret on argv:
 *
 *  - the **spec file** (`<attempt>/mcp/x-<id>.launch.json`, 0600, removed with the attempt) holds the executable (an
 *    npm bin script run by the launcher's Node, or a PyPI console script inside the install's venv), the signed
 *    spec's fixed args and the server's env (literals, and secret values read from this worker's vault);
 *  - the **launcher** starts it with an env built from an allowlist of the inherited variables (PATH, HOME, temp,
 *    locale, proxy, CA bundle — what the sandbox set for the attempt) plus the spec's env: provider keys, other
 *    servers' secrets and the runtime's own variables never reach the server, whatever the runtime passes down
 *    (Claude Code / OpenCode / Pi pass their whole environment, Codex a fixed default set plus `env_vars`).
 *  - It forwards termination signals and exits with the server's code; stdio is inherited (the MCP channel).
 */

export const MCP_LAUNCHER_FILE = 'remyral-mcp-launch.mjs';

