/** Source of the launcher (plain ESM, no dependencies; the allowlist is inlined). */
export function mcpLauncherSource(): string {
  return `// Generated by the Remyral worker (p14-mcp-stdio). Do not edit.
import { spawn } from 'node:child_process';
import { readFileSync } from 'node:fs';
const KEEP = ${JSON.stringify(MCP_LAUNCH_ENV_ALLOWLIST)};
const fail = (msg) => { process.stderr.write('remyral-mcp-launch: ' + msg + '\\n'); process.exit(127); };
const file = process.argv[2];
if (typeof file !== 'string' || process.argv.length !== 3) fail('usage: remyral-mcp-launch <spec file>');
let spec;
try { spec = JSON.parse(readFileSync(file, 'utf8')); } catch { fail('cannot read the launch spec'); }
if (spec.v !== 1 || typeof spec.exec?.file !== 'string' || !Array.isArray(spec.args)) fail('invalid launch spec');
const env = {};
for (const k of KEEP) { const v = process.env[k]; if (typeof v === 'string') env[k] = v; }
for (const [k, v] of Object.entries(spec.env ?? {})) if (typeof v === 'string') env[k] = v;
const cmd = spec.exec.kind === 'node' ? process.execPath : spec.exec.file;
const args = spec.exec.kind === 'node' ? [spec.exec.file, ...spec.args] : [...spec.args];
const child = spawn(cmd, args, { stdio: 'inherit', env, shell: false, windowsHide: true });
for (const sig of ['SIGTERM', 'SIGINT', 'SIGHUP']) {
  try { process.on(sig, () => { try { child.kill(sig); } catch {} }); } catch {}
}
child.on('error', (e) => fail('cannot start the server (' + (e && e.code ? e.code : 'spawn failed') + ')'));
child.on('exit', (code, signal) => process.exit(code ?? (signal ? 1 : 0)));
`;
}

export interface McpLaunchSpec {
  readonly v: 1;
  readonly exec: McpServerExec;
  readonly args: readonly string[];
  readonly env: Readonly<Record<string, string>>;
}

/** The env of one server: literals as written, secret slots resolved from the attempt's MCP secrets. */
export function mcpServerEnv(
  spec: McpSpec,
  secretEnv: Readonly<Record<string, SecretString>>,
): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [name, value] of Object.entries(spec.stdio?.env ?? {})) {
    if (typeof value === 'string') {
      out[name] = value;
      continue;
    }
    const secret = secretEnv[mcpSecretEnvName(spec.id, value.secret)];
    if (secret === undefined) throw new Error(`mcp_secret_missing: ${spec.id}/${value.secret}`);
    const [pre = '', post = ''] = (value.format ?? '{}').split('{}');
    out[name] = `${pre}${secret.reveal()}${post}`;
  }
  return out;
}

/** Writes the launcher (once per attempt) and one 0600 spec file per server; returns the spec file path. */
export async function writeMcpLaunch(
  configDir: string,
  spec: McpSpec,
  exec: McpServerExec,
  env: Readonly<Record<string, string>>,
): Promise<{ readonly launcher: string; readonly specFile: string }> {
  const launcher = join(configDir, MCP_LAUNCHER_FILE);
  await writeFile(launcher, mcpLauncherSource(), { mode: 0o600 });
  await chmod(launcher, 0o600);
  const launch: McpLaunchSpec = { v: 1, exec, args: [...(spec.stdio?.args ?? [])], env };
  const specFile = join(configDir, `${mcpRuntimeName(spec.id)}.launch.json`);
  await writeFile(specFile, `${JSON.stringify(launch)}\n`, { mode: 0o600 });
  await chmod(specFile, 0o600);
  return { launcher, specFile };
}
