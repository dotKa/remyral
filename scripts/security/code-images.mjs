#!/usr/bin/env node
// Code node build contexts shipped in the worker release (p14-code-images, docs/design/p14-followups.md §2):
//
//   node scripts/security/code-images.mjs [--write | --check]
//
// Embeds infra/worker/images/code-js|code-python (Dockerfile + runner) into
// apps/worker/src/functions/code-images.generated.ts, so the worker's `code.images.prepare` remote op builds exactly
// the reviewed contexts (no repository checkout on the worker host). Also checks that each Dockerfile has exactly one
// FROM and that it equals the pinned digest of FUNCTION_CODE_BASE_IMAGES (packages/protocol/src/function-job.ts).
// --check (in `pnpm security:pins`) fails when the generated file is stale or a pin differs.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { REPO, readText } from './lib.mjs';

export const OUT = 'apps/worker/src/functions/code-images.generated.ts';
const CONTEXTS = {
  js: { dir: 'infra/worker/images/code-js', runner: 'run.mjs' },
  python: { dir: 'infra/worker/images/code-python', runner: 'run.py' },
};

/** FUNCTION_CODE_BASE_IMAGES as written in the protocol source (string literals only). */
export function pinnedBases(source = readText('packages/protocol/src/function-job.ts')) {
  const block = /export const FUNCTION_CODE_BASE_IMAGES = \{([\s\S]*?)\} as const;/.exec(source)?.[1];
  if (block === undefined) throw new Error('FUNCTION_CODE_BASE_IMAGES not found');
  const out = {};
  for (const m of block.matchAll(/^\s*(\w+):\s*'([^']+)',?$/gm)) out[m[1]] = m[2];
  for (const lang of Object.keys(CONTEXTS)) {
    if (!/^[a-z0-9./_-]+:[A-Za-z0-9._-]+@sha256:[0-9a-f]{64}$/.test(out[lang] ?? ''))
      throw new Error(`FUNCTION_CODE_BASE_IMAGES.${lang} is not pinned by digest`);
  }
  return out;
}

const sha256 = (text) => createHash('sha256').update(text, 'utf8').digest('hex');

export function buildContexts() {
  const bases = pinnedBases();
  const out = {};
  for (const [lang, c] of Object.entries(CONTEXTS)) {
    const dockerfile = readText(`${c.dir}/Dockerfile`);
    const froms = dockerfile.split('\n').filter((l) => /^\s*FROM\s/i.test(l));
    if (froms.length !== 1) throw new Error(`${c.dir}/Dockerfile: exactly one FROM expected`);
    const from = froms[0].trim().split(/\s+/)[1];
    if (from !== bases[lang]) throw new Error(`${c.dir}/Dockerfile: FROM ${from} != pinned ${bases[lang]}`);
    if (/^\s*(ADD|ARG)\s/im.test(dockerfile)) throw new Error(`${c.dir}/Dockerfile: ADD / ARG not allowed`);
    const runner = readText(`${c.dir}/${c.runner}`);
    out[lang] = {
      base: bases[lang],
      dockerfile,
      dockerfileSha256: sha256(dockerfile),
      runnerName: c.runner,
      runner,
      runnerSha256: sha256(runner),
    };
  }
  return out;
}

export function render(contexts = buildContexts()) {
  return [
    '// GENERATED by scripts/security/code-images.mjs from infra/worker/images/code-js|code-python — do not edit.',
    '// `pnpm security:pins` fails when it is stale or a Dockerfile FROM differs from FUNCTION_CODE_BASE_IMAGES.',
    "import type { CodeImageContexts } from './code-images.js';",
    '',
    `export const CODE_IMAGE_CONTEXTS: CodeImageContexts = ${JSON.stringify(contexts, null, 2)};`,
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { values } = parseArgs({
    options: { write: { type: 'boolean', default: false }, check: { type: 'boolean', default: false } },
  });
  const text = render();
  const path = join(REPO, OUT);
  if (values.write) {
    writeFileSync(path, text);
    console.log(`code-images: wrote ${OUT}`);
  } else {
    let current = '';
    try {
      current = readFileSync(path, 'utf8');
    } catch {
      // missing
    }
    if (current !== text) {
      console.error(`code-images: ${OUT} is stale — run node scripts/security/code-images.mjs --write`);
      process.exit(1);
    }
    console.log('code-images: build contexts embedded and pinned by digest');
  }
}
