import { randomUUID } from 'node:crypto';

let seq = 0;

export function envelope<E extends Record<string, unknown>>(type: string, extra: E = {} as E) {
  return {
    protocolVersion: '1.0',
    type,
    messageId: randomUUID(),
    seq: seq++,
    ts: '2026-10-12T19:00:00.000Z',
    correlationId: 'corr-1',
    ...extra,
  };
}

