import { mkdir, readdir, readFile, rename, rm, stat, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { isJobChannelTool, type JobToolChannel, runJobChannelTool } from '../../deploy-tools.js';
import { SUBTASK_MCP_SERVER, type SubtaskToolHost, type SubtaskToolSpec } from '../../subtask-tools.js';

/**
 * p11-fixes-a (docs/design/p11-merge-pipeline.md §10): the sub-job tools for OpenCode 1.19.0 — without a new hole in
 * any job sandbox.
 *
 * OpenCode starts a **local (stdio) MCP server** itself (`mcp.<name>: {type: "local", command}`): the OpenCode binary in
 * Bun mode (`BUN_BE_BUN=1`, no Node needed in the sandbox) running a script the adapter generated. It is a child of the
 * confined OpenCode process, so it inherits exactly its sandbox. Its tool calls are relayed through **files** in a
 * directory inside the attempt's private runtime state dir — which every job profile already lets the runtime write
 * (Seatbelt, bubblewrap, Windows per-job accounts; containers mount it at the same path) — and answered by the adapter
 * on the host from `SpawnContext.subtaskTools`. No socket, no port, no loopback connect.
 *
 * Trust: anything inside the sandbox may write a request file — exactly as the agent itself may call the tools. Each
 * request is size-capped, validated with the same zod schemas as every other runtime ({@link runSubtaskTool}), the
 * number of calls in flight is capped, and the master still decides every sub-job (ADR-0031).
 */

export const OPENCODE_SUBTASK_SCRIPT = 'remyral-subtasks-mcp.mjs';
export const OPENCODE_SUBTASK_RELAY_DIR = 'subtask-relay';
/** OpenCode names MCP tools `<server>_<tool>`; the permission rule allows exactly these. */
export const OPENCODE_SUBTASK_TOOL_PATTERN = `${SUBTASK_MCP_SERVER}_*`;

const MAX_REQUEST_BYTES = 256 * 1024;
const MAX_INFLIGHT = 8;
const ID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

/**
 * The MCP server script (ESM, no dependencies; runs on Bun or Node). It speaks newline-delimited JSON-RPC on stdio
 * (MCP stdio transport): `initialize`, `tools/list`, `tools/call`, `ping`. A call writes `<id>.req.json` atomically
 * (temp file + rename) and waits for `<id>.res.json`. `waitCapSec` bounds the waits of one call (`waitSec` of
 * `request_subtask` / `wait_subtask`); the tools' own text tells the agent to call `wait_subtask` again.
 */
export function opencodeSubtaskServerSource(
  specs: readonly SubtaskToolSpec[],
  relayDir: string,
  waitCapSec: number,
): string {
  const tools = specs.map((s) => ({ name: s.name, description: s.description, inputSchema: s.inputSchema }));
  return `// Generated by the Remyral worker (p11-fixes-a): sub-job tools for OpenCode, relayed through files.
import { randomUUID } from 'node:crypto';
import { existsSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const DIR = ${JSON.stringify(relayDir)};
const TOOLS = ${JSON.stringify(tools)};
const WAIT_CAP = ${String(Math.max(0, Math.floor(waitCapSec)))};

function send(msg) {
  process.stdout.write(JSON.stringify({ jsonrpc: '2.0', ...msg }) + '\\n');
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function call(name, args) {
  const a = args && typeof args === 'object' && !Array.isArray(args) ? { ...args } : {};
  if ((name === 'request_subtask' || name === 'wait_subtask' || name === 'ask_user' || name === 'wait_for_answer') && WAIT_CAP > 0) {
    const asked = typeof a.waitSec === 'number' ? a.waitSec : 540;
    if (asked > WAIT_CAP) a.waitSec = WAIT_CAP;
  }
  const id = randomUUID();
  const tmp = join(DIR, id + '.req.tmp');
  writeFileSync(tmp, JSON.stringify({ id, tool: name, args: a }));
  renameSync(tmp, join(DIR, id + '.req.json'));
  const res = join(DIR, id + '.res.json');
  for (;;) {
    if (existsSync(res)) {
      try {
        const out = JSON.parse(readFileSync(res, 'utf8'));
        rmSync(res, { force: true });
        return { ok: out.ok === true, text: String(out.text ?? '') };
      } catch {
        // written but not complete yet (never: the adapter renames) — retry
      }
    }
    await sleep(150);
  }
}

async function handle(msg) {
  const { id, method, params } = msg;
  if (id === undefined || id === null) return; // notifications
  switch (method) {
    case 'initialize':
      send({
        id,
        result: {
          protocolVersion: (params && params.protocolVersion) || '2025-06-18',
          capabilities: { tools: {} },
          serverInfo: { name: ${JSON.stringify(SUBTASK_MCP_SERVER)}, version: '1.0.0' },
        },
      });
      return;
    case 'ping':
      send({ id, result: {} });
      return;
    case 'tools/list':
      send({ id, result: { tools: TOOLS } });
      return;
    case 'tools/call': {
      const name = params && params.name;
      if (!TOOLS.some((t) => t.name === name)) {
        send({ id, result: { content: [{ type: 'text', text: 'unknown tool' }], isError: true } });
        return;
      }
      const out = await call(name, params.arguments);
      send({ id, result: { content: [{ type: 'text', text: out.text }], isError: !out.ok } });
      return;
    }
    default:
      send({ id, error: { code: -32601, message: 'method not found' } });
  }
}

let buf = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', (chunk) => {
  buf += chunk;
  let nl;
  while ((nl = buf.indexOf('\\n')) >= 0) {
    const line = buf.slice(0, nl).trim();
    buf = buf.slice(nl + 1);
    if (line === '') continue;
    let msg;
    try {
      msg = JSON.parse(line);
    } catch {
      continue;
    }
    void handle(msg).catch((err) => {
      if (msg && msg.id !== undefined) send({ id: msg.id, error: { code: -32603, message: String(err && err.message || err) } });
    });
  }
});
process.stdin.on('end', () => process.exit(0));
`;
}

export interface SubtaskFileRelayOptions {
  readonly dir: string;
  /** The sub-job tools (kept for callers that only relay those). */
  readonly host?: SubtaskToolHost;
  /** p12-deploy-feedback: the job's whole tool channel (sub-job and / or deploy tools); wins over `host`. */
  readonly channel?: JobToolChannel;
  /** Aborted when the session stops (ends a call that still waits). */
  readonly signal: AbortSignal;
  readonly pollMs?: number;
  readonly onCall?: (tool: string, ok: boolean) => void;
}

/** The host side: answers the request files of one session from the worker's {@link SubtaskToolHost}. */
export class SubtaskFileRelay {
  readonly #o: SubtaskFileRelayOptions;
  #timer: NodeJS.Timeout | undefined;
  #scanning = false;
  readonly #inflight = new Set<string>();

  constructor(o: SubtaskFileRelayOptions) {
    this.#o = o;
  }

  static async prepare(dir: string): Promise<void> {
    await rm(dir, { recursive: true, force: true });
    await mkdir(dir, { recursive: true, mode: 0o700 });
  }

  start(): void {
    if (this.#timer !== undefined) return;
    this.#timer = setInterval(() => {
      void this.scan();
    }, this.#o.pollMs ?? 150);
    this.#timer.unref();
    this.#o.signal.addEventListener('abort', () => {
      this.stop();
    });
  }

  stop(): void {
    if (this.#timer !== undefined) clearInterval(this.#timer);
    this.#timer = undefined;
  }

  /** One pass over the directory (also called by tests). */
  async scan(): Promise<void> {
    if (this.#scanning || this.#o.signal.aborted) return;
    this.#scanning = true;
    try {
      const names = await readdir(this.#o.dir).catch(() => [] as string[]);
      for (const name of names) {
        if (!name.endsWith('.req.json')) continue;
        const id = name.slice(0, -'.req.json'.length);
        const file = join(this.#o.dir, name);
        if (!ID.test(id) || this.#inflight.has(id)) {
          await rm(file, { force: true });
          continue;
        }
        const size = (await stat(file).catch(() => null))?.size ?? 0;
        const raw = size > MAX_REQUEST_BYTES ? null : await readFile(file, 'utf8').catch(() => null);
        await rm(file, { force: true });
        if (this.#inflight.size >= MAX_INFLIGHT) {
          await this.#answer(id, { ok: false, text: 'too many sub-job tool calls at once; try again' });
          continue;
        }
        this.#inflight.add(id);
        void this.#run(id, raw).finally(() => this.#inflight.delete(id));
      }
    } finally {
      this.#scanning = false;
    }
  }

  async #run(id: string, raw: string | null): Promise<void> {
    let out: { ok: boolean; text: string };
    let tool = 'unknown';
    try {
      const req = raw === null ? null : (JSON.parse(raw) as { tool?: unknown; args?: unknown });
      const channel: JobToolChannel = this.#o.channel ?? { subtaskTools: this.#o.host };
      if (req === null || typeof req.tool !== 'string' || !isJobChannelTool(channel, req.tool)) {
        out = { ok: false, text: 'invalid sub-job tool request' };
      } else {
        tool = req.tool;
        const args =
          typeof req.args === 'object' && req.args !== null && !Array.isArray(req.args)
            ? (req.args as Record<string, unknown>)
            : {};
        out = await runJobChannelTool(channel, req.tool, args, this.#o.signal);
      }
    } catch (err) {
      out = { ok: false, text: `sub-job tool failed: ${err instanceof Error ? err.message : 'error'}` };
    }
    this.#o.onCall?.(tool, out.ok);
    if (!this.#o.signal.aborted) await this.#answer(id, out);
  }

  async #answer(id: string, out: { ok: boolean; text: string }): Promise<void> {
    const tmp = join(this.#o.dir, `${id}.res.tmp`);
    await writeFile(tmp, JSON.stringify(out), { mode: 0o600 });
    await rename(tmp, join(this.#o.dir, `${id}.res.json`));
  }
}
