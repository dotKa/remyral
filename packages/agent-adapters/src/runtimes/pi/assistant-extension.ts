import type { AssistantToolSpec } from '../../assistant-kit.js';

/**
 * The ops chat tool bridge for Pi 1.1.0 (p5-ops-chat-next, docs/compat/pi.md §12). Pi has no client-side tool
 * channel in RPC mode, but its extensions can register tools and, in RPC mode, every `ctx.ui` dialog becomes an
 * `extension_ui_request` on stdout that the client answers with an `extension_ui_response` on stdin
 * (docs/rpc-extension-ui.md). The bridge uses exactly that: each platform tool is registered with
 * `pi.registerTool` (plain JSON Schema parameters — accepted and validated by the pinned binary, verified
 * 2026-10-16); its `execute` asks an `input` dialog whose title is `PI_ASSISTANT_MARKER` + `{callId, tool,
 * input}` JSON, with the tool's abort signal and a timeout; the engine answers with the result
 * (`{content, isError}` JSON) after relaying the call to the master. No port, no process, no file I/O.
 *
 * Fail closed: a `tool_call` handler blocks every tool that is not a platform tool (Pi treats a handler
 * failure as a block too); no answer, a cancelled dialog, an unparsable answer or a missing UI channel all
 * become error results for the model. The source is plain ESM without imports (Pi's loader needs nothing from
 * the workspace); the engine writes it 0600 into the session's private state directory and loads it with
 * `--no-extensions -e <path>`.
 */

export const PI_ASSISTANT_MARKER = 'remyral-assistant-tool:v1:';
export const PI_ASSISTANT_EXTENSION_FILE = 'remyral-assistant-tools.mjs';

/** Payload carried in the dialog title after `PI_ASSISTANT_MARKER`. */
export interface PiAssistantToolRequest {
  readonly callId: string;
  readonly tool: string;
  readonly input: unknown;
}

/** The dialog answer (JSON in `extension_ui_response.value`). */
export interface PiAssistantToolAnswer {
  readonly content: string;
  readonly isError: boolean;
}

/** Generates the bridge extension for these tools; `timeoutMs` bounds each relayed call on Pi's side. */
export function piAssistantExtensionSource(tools: readonly AssistantToolSpec[], timeoutMs: number): string {
  const specs = tools.map((t) => ({ name: t.name, description: t.description, parameters: t.inputSchema }));
  return `// Generated by @remyral/agent-adapters (Pi ops chat tool bridge). Do not edit.
const MARKER = ${JSON.stringify(PI_ASSISTANT_MARKER)};
const TIMEOUT_MS = ${String(Math.max(1_000, Math.floor(timeoutMs)))};
const TOOLS = ${JSON.stringify(specs)};
const NAMES = new Set(TOOLS.map((t) => t.name));
function fail(text) {
  return { content: [{ type: 'text', text }], details: undefined, isError: true };
}
export default function remyralAssistantTools(pi) {
  for (const spec of TOOLS) {
    pi.registerTool({
      name: spec.name,
      label: spec.name,
      description: spec.description,
      parameters: spec.parameters,
      async execute(toolCallId, params, signal, _onUpdate, ctx) {
        try {
          if (!ctx || !ctx.hasUI || !ctx.ui) return fail('The platform tool channel is not available.');
          const title = MARKER + JSON.stringify({ callId: String(toolCallId).slice(0, 256), tool: spec.name, input: params ?? {} });
          const opts = { timeout: TIMEOUT_MS };
          if (signal) opts.signal = signal;
          const answer = await ctx.ui.input(title, '', opts);
          if (typeof answer !== 'string') return fail('The platform did not answer this tool call (cancelled or timed out).');
          let parsed;
          try { parsed = JSON.parse(answer); } catch { return fail('The platform answered this tool call unreadably.'); }
          if (!parsed || typeof parsed.content !== 'string') return fail('The platform answered this tool call unreadably.');
          return { content: [{ type: 'text', text: parsed.content }], details: undefined, isError: parsed.isError === true };
        } catch {
          return fail('The platform tool call failed.');
        }
      },
    });
  }
  pi.on('tool_call', async (event) => {
    try {
      if (event && NAMES.has(event.toolName)) return undefined;
      return { block: true, reason: 'Blocked by Remyral: only the remyral platform tools exist in the ops chat.' };
    } catch {
      return { block: true, reason: 'Blocked by Remyral (fail-closed).' };
    }
  });
}
`;
}
