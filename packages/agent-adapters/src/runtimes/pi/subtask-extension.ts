import { SUBTASK_LIMITS } from '@remyral/protocol';
import type { SubtaskToolSpec } from '../../subtask-tools.js';

/**
 * p8-subtasks-pi (ADR-0031): the sub-job tools of a Pi 1.1.0 job, over the same channel as the ops chat tool bridge
 * (assistant-extension.ts, docs/compat/pi.md §12): Pi has no client-side tool channel in RPC mode, but an extension can
 * register tools (`pi.registerTool`, plain JSON Schema parameters) and, in RPC mode, every `ctx.ui` dialog becomes an
 * `extension_ui_request` on stdout that the adapter answers with an `extension_ui_response` on stdin. Each sub-job tool's
 * `execute` asks an `input` dialog whose title is {@link PI_SUBTASK_MARKER} + `{callId, tool, input}` JSON (with the
 * tool's abort signal and a timeout that covers the longest wait); the adapter runs the call on the worker's
 * SubtaskToolHost and answers `{content, isError}` JSON. No port, no process, no file I/O.
 *
 * The permission gate (gate-extension.ts) lets exactly these tool names through without asking (`preApprovedTools`):
 * the master's gates decide, as for Claude Code and Codex. No answer, a cancelled dialog, an unparsable answer or a
 * missing UI channel become error results for the model. Plain ESM without imports; written 0600 into the session's
 * private run dir and loaded with `-e <path>` after the gate.
 */

export const PI_SUBTASK_MARKER = 'remyral-subtask-tool:v1:';
export const PI_SUBTASK_EXTENSION_FILE = 'remyral-subtask-tools.mjs';

/** A sub-job call waits up to `maxWaitSec` on the worker; the dialog allows that plus a minute for the answer. */
export const PI_SUBTASK_DIALOG_TIMEOUT_MS = (SUBTASK_LIMITS.maxWaitSec + 60) * 1000;

/** Payload carried in the dialog title after `PI_SUBTASK_MARKER`. */
export interface PiSubtaskToolRequest {
  readonly callId: string;
  readonly tool: string;
  readonly input: unknown;
}

/** The dialog answer (JSON in `extension_ui_response.value`). */
export interface PiSubtaskToolAnswer {
  readonly content: string;
  readonly isError: boolean;
}

/** Generates the extension registering these tools. */
export function piSubtaskExtensionSource(
  tools: readonly SubtaskToolSpec[],
  timeoutMs = PI_SUBTASK_DIALOG_TIMEOUT_MS,
): string {
  const specs = tools.map((t) => ({ name: t.name, description: t.description, parameters: t.inputSchema }));
  return `// Generated by @remyral/agent-adapters (Pi sub-job tools). Do not edit.
const MARKER = ${JSON.stringify(PI_SUBTASK_MARKER)};
const TIMEOUT_MS = ${String(Math.max(1_000, Math.floor(timeoutMs)))};
const TOOLS = ${JSON.stringify(specs)};
function fail(text) {
  return { content: [{ type: 'text', text }], details: undefined, isError: true };
}
export default function remyralSubtaskTools(pi) {
  for (const spec of TOOLS) {
    pi.registerTool({
      name: spec.name,
      label: spec.name,
      description: spec.description,
      parameters: spec.parameters,
      async execute(toolCallId, params, signal, _onUpdate, ctx) {
        try {
          if (!ctx || !ctx.hasUI || !ctx.ui) return fail('The platform tool channel is not available.');
          const title = MARKER + JSON.stringify({ callId: String(toolCallId).slice(0, 256), tool: spec.name, input: params ?? {} });
          const opts = { timeout: TIMEOUT_MS };
          if (signal) opts.signal = signal;
          const answer = await ctx.ui.input(title, '', opts);
          if (typeof answer !== 'string') return fail('The platform did not answer this tool call (cancelled or timed out).');
          let parsed;
          try { parsed = JSON.parse(answer); } catch { return fail('The platform answered this tool call unreadably.'); }
          if (!parsed || typeof parsed.content !== 'string') return fail('The platform answered this tool call unreadably.');
          return { content: [{ type: 'text', text: parsed.content }], details: undefined, isError: parsed.isError === true };
        } catch {
          return fail('The platform tool call failed.');
        }
      },
    });
  }
}
`;
}
